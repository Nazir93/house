export const getPublicFaqs = unstable_cache(
  async (): Promise<PublicFaqItem[]> => {
    try {
      const rows = await prisma.faq.findMany({
        where: { visible: true },
        orderBy: { order: "asc" },
        select: { id: true, question: true, answer: true },
      });
      if (rows.length > 0) {
        return rows.map((r) => ({
          id: r.id,
          q: htmlToPlainText(r.question) || r.question,
          a: htmlToPlainText(r.answer) || r.answer,
        }));
      }
    } catch {
      /* DB недоступна */
    }
    return FALLBACK_PUBLIC_FAQS;
  },
  ["public-faqs"],
  { revalidate: 60, tags: [CACHE_TAG_PUBLIC_FAQS] }
);
