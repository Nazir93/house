export function getProjectMaterialSeo(slug: string): ProjectMaterialSeo | null {
  return PROJECT_MATERIAL_SEO[slug as ProjectMaterialSeoSlug] ?? null;
}

export function getProjectMaterialSeoSlugs(): ProjectMaterialSeoSlug[] {
  return Object.keys(PROJECT_MATERIAL_SEO) as ProjectMaterialSeoSlug[];
}

export function getProjectMaterialSeoPages(): ProjectMaterialSeo[] {
  return getProjectMaterialSeoSlugs().map((slug) => PROJECT_MATERIAL_SEO[slug]);
}

export function getProjectMaterialPageMetaSeeds(): Array<{
  path: string;
  title: string;
  description: string;
  keywords: string;
  h1: string;
}> {
  return getProjectMaterialSeoPages().map((seo) => ({
    path: seo.path,
    title: seo.title,
    description: seo.description,
    keywords: seo.keywords.join(", "),
    h1: seo.h1,
  }));
}
